function knowledgePointOptions(subject, current, existing){
  var groups = KNOWLEDGE_POINTS[subject] || {}, seen = {}, html = '';
  function option(value){
    var safe = String(value).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
    return '<option value="' + safe + '"' + (current === value ? ' selected' : '') + '>' + safe + '</option>';
  }
  html += option('待归类');
  seen['待归类'] = true;
  Object.keys(groups).forEach(function(group){
    html += '<optgroup label="' + group + '">';
    groups[group].forEach(function(point){ seen[point] = true; html += option(point); });
    html += '</optgroup>';
  });
  var other = (existing || []).slice();
  if(current) other.push(current);
  other = other.filter(function(point){ if(!point || seen[point]) return false; seen[point] = true; return true; });
  if(other.length) html += '<optgroup label="已有知识点">' + other.map(option).join('') + '</optgroup>';
  return html;
}
